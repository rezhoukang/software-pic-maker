const library=JSON.parse(fs.readFileSync(new URL('../../shared/library.json',import.meta.url),'utf8'))

test('compact flowchart keeps the positive branch straight and merges without a dot',async({page})=>{
 await page.goto('/');await page.locator('.diagram-nav[data-type="flowchart"]').first().click()
 await expect(page.locator('.x6-node[data-cell-id="$junction:finish"]')).toBeVisible()
 const line=(id:string)=>page.locator(`.x6-edge[data-cell-id="${id}"] path`).nth(1)
 for(const id of ['f5','f6'])expect((await line(id).getAttribute('marker-end'))||'').not.toMatch(/url\(/)
 await expect(line('$junction-edge:finish')).toHaveAttribute('marker-end',/url\(/)
 const node=await page.locator('.x6-node[data-cell-id="check"]').boundingBox();expect(node).not.toBeNull()
 for(const id of ['f3','f4']){
  const start=await line(id).evaluate((element)=>{const path=element as SVGPathElement;const point=path.getPointAtLength(0);const screen=new DOMPoint(point.x,point.y).matrixTransform(path.getScreenCTM()!);return{x:screen.x,y:screen.y}})
  const scale=node!.width/230;const x=id==='f3'?node!.x+node!.width/2:node!.x+node!.width-2*scale
  const y=id==='f3'?node!.y+node!.height-2*scale:node!.y+node!.height/2
  expect(Math.abs(start.x-x)).toBeLessThan(1);expect(Math.abs(start.y-y)).toBeLessThan(1)
 }
 const yes=await page.getByText('是',{exact:true}).boundingBox();const no=await page.getByText('否',{exact:true}).boundingBox()
 expect(yes!.y).toBeGreaterThan(node!.y+node!.height);expect(no!.x).toBeGreaterThan(node!.x+node!.width)
 const junction=page.locator('.x6-node[data-cell-id="$junction:finish"] image')
 expect(decodeURIComponent((await junction.getAttribute('xlink:href'))||'')).not.toContain('<circle')
 const main=await page.locator('.x6-node[data-cell-id="save"]').boundingBox()
 expect(Math.abs(main!.x+main!.width/2-node!.x-node!.width/2)).toBeLessThan(1)
 await page.locator('.canvas-area').screenshot({path:'test-results/flowchart-arrow-positions.png'})
})

