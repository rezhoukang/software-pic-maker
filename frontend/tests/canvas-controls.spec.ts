import { test, expect } from '@playwright/test'

test('canvas fullscreen and inspector collapse have separate controls and restore their state', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.x6-node').first()).toBeVisible()
  const toolbar = page.locator('.editor-toolbar')
  const inspector = page.locator('.inspector')
  await expect(toolbar.getByRole('button', { name: '收起属性面板', exact: true })).toHaveCount(0)
  const width = await page.locator('.canvas-area').evaluate(el => el.clientWidth)
  await inspector.getByRole('button', { name: '收起属性面板', exact: true }).click()
  await expect(inspector).toHaveCount(0)
  await expect.poll(() => page.locator('.canvas-area').evaluate(el => el.clientWidth)).toBeGreaterThan(width)
  await expect(page.locator('.sidebar')).toBeVisible()
  await page.getByRole('button', { name: '展开属性面板', exact: true }).click()
  await expect(inspector).toBeVisible()
  await toolbar.getByRole('button', { name: '全屏画布', exact: true }).click()
  await expect(page.locator('.sidebar')).toBeHidden()
  await expect(inspector).toBeHidden()
  await expect(page.locator('.canvas-area')).toHaveJSProperty('clientWidth', 1480)
  await expect(toolbar.getByRole('button', { name: '退出全屏', exact: true }).locator('svg')).toHaveClass(/lucide-minimize/)
  await toolbar.getByRole('button', { name: '退出全屏', exact: true }).click()
  await expect(page.locator('.sidebar')).toBeVisible()
  await expect(inspector).toBeVisible()
  const fit = page.getByRole('button', { name: '适应画布', exact: true })
  await expect(fit.locator('svg')).toHaveClass(/lucide-circle-dot/)
  await fit.click()
  await inspector.getByRole('button', { name: '收起属性面板', exact: true }).click()
  await toolbar.getByRole('button', { name: '全屏画布', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.locator('.sidebar')).toBeVisible()
  await expect(inspector).toHaveCount(0)
  await expect(page.getByRole('button', { name: '展开属性面板', exact: true })).toBeVisible()
  await expect(page.getByTestId('file-save-status')).toContainText('已保存')
})

test('file manager can collapse independently and toolbar orders fullscreen before history', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.x6-node').first()).toBeVisible()
  const search = page.getByRole('textbox', { name: '搜索文件或文件夹', exact: true })
  await search.fill('图书')
  const width = await page.locator('.canvas-area').evaluate(el => el.clientWidth)
  await page.getByRole('button', { name: '收起文件管理', exact: true }).click()
  await expect(page.locator('.sidebar')).toBeHidden()
  await expect(page.locator('.inspector')).toBeVisible()
  await expect.poll(() => page.locator('.canvas-area').evaluate(el => el.clientWidth)).toBeGreaterThan(width)
  await page.getByRole('button', { name: '展开文件管理', exact: true }).click()
  await expect(search).toHaveValue('图书')
  const full = page.getByRole('button', { name: '全屏画布', exact: true })
  const undo = page.getByRole('button', { name: '撤销', exact: true })
  const redo = page.getByRole('button', { name: '重做', exact: true })
  expect((await full.boundingBox())!.x).toBeLessThan((await undo.boundingBox())!.x)
  expect((await undo.boundingBox())!.x).toBeLessThan((await redo.boundingBox())!.x)
  await page.getByRole('button', { name: '收起文件管理', exact: true }).click()
  await full.click()
  await expect(page.locator('.file-manager-rail')).toHaveCount(0)
  await page.getByRole('button', { name: '退出全屏', exact: true }).click()
  await expect(page.getByRole('button', { name: '展开文件管理', exact: true })).toBeVisible()
  await expect(page.locator('.sidebar')).toBeHidden()
  await expect(page.getByTestId('file-save-status')).toContainText('已保存')
})
