import { test, expect } from '@playwright/test'

test('cardinality edits and selecting a relation undo and redo as separate operations', async ({ page }) => {
  await page.goto('/')
  const relation = page.locator('.x6-node[data-cell-id="$relation:belongs"]')
  await expect(relation).toBeVisible()
  const undo = page.getByRole('button', { name: '撤销', exact: true })
  const redo = page.getByRole('button', { name: '重做', exact: true })
  await expect(undo).toBeDisabled()
  await relation.click()
  const source = page.locator('.form-label').filter({ hasText: '起点基数' }).locator('.n-base-selection')
  const target = page.locator('.form-label').filter({ hasText: '终点基数' }).locator('.n-base-selection')
  await expect(source).toHaveText('N')
  await expect(page.getByTestId('file-save-status')).toContainText('已保存')
  await source.click()
  await expect(page.locator('.n-base-select-option:visible')).toHaveText(['1', '0..1', '0..N', '1..N', 'N', 'M'])
  await page.locator('.n-base-select-option:visible').filter({ hasText: /^0\.\.1$/ }).click()
  await expect(source).toHaveText('0..1')
  await target.click()
  await expect(page.locator('.n-base-select-option:visible')).toHaveText(['1', '0..1', '0..N', '1..N', 'N', 'M'])
  await page.locator('.n-base-select-option:visible').filter({ hasText: /^1$/ }).click()
  // Choosing the same value must not add a redundant edit to history.
  await undo.click()
  await expect(source).toHaveText('N')
  await expect(page.locator('.inspector')).toContainText('选中连线')
  await undo.click()
  await expect(page.locator('.inspector')).toContainText('基本信息')
  await expect(undo).toBeDisabled()
  await redo.click()
  await expect(source).toHaveText('N')
  await redo.click()
  await expect(source).toHaveText('0..1')
  await expect(redo).toBeDisabled()
})

test('selection history keeps a saved file clean and restores previous selection', async ({ page }) => {
  await page.goto('/')
  const reader = page.locator('.x6-node[data-cell-id="reader"]')
  const book = page.locator('.x6-node[data-cell-id="book"]')
  const undo = page.getByRole('button', { name: '撤销', exact: true })
  const redo = page.getByRole('button', { name: '重做', exact: true })
  const heading = page.locator('.property-heading strong')
  await reader.click()
  await book.click()
  await undo.click()
  await expect(heading).toHaveText('读者')
  await undo.click()
  await expect(page.locator('.inspector')).toContainText('基本信息')
  await redo.click()
  await expect(heading).toHaveText('读者')
  await redo.click()
  await expect(heading).toHaveText('图书')
  await page.keyboard.press('Escape')
  await expect(page.locator('.inspector')).toContainText('基本信息')
  await undo.click()
  await expect(heading).toHaveText('图书')
  await expect(page.getByTestId('file-save-status')).toContainText('已保存')
  await book.click()
  // Clicking the already selected item must preserve redo.
  await expect(redo).toBeEnabled()
})

test('undoing deletion restores both content and the selected item', async ({ page }) => {
  await page.goto('/')
  const reader = page.locator('.x6-node[data-cell-id="reader"]')
  await reader.click()
  await page.getByRole('button', { name: '删除元素及相关连线', exact: true }).click()
  await expect(reader).toHaveCount(0)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(reader).toBeVisible()
  await expect(page.locator('.property-heading strong')).toHaveText('读者')
  await page.getByRole('button', { name: '重做', exact: true }).click()
  await expect(reader).toHaveCount(0)
  await expect(page.locator('.inspector')).toContainText('基本信息')
})
