import { test, expect } from '@playwright/test'

test('use-case system title can be selected, renamed and undone independently of file title', async ({ page }) => {
  await page.goto('/')
  await page.locator('.diagram-nav[data-type="usecase"]').first().click()
  const boundary = page.locator('.x6-node[data-cell-id="$boundary"]')
  await expect(boundary).toBeVisible()
  await page.locator('.x6-node[data-cell-id="reader"]').click()
  await expect(page.getByRole('textbox', { name: '系统名称', exact: true })).toHaveCount(0)
  await boundary.locator('rect').last().click()
  const name = page.getByRole('textbox', { name: '系统名称', exact: true })
  const original = await name.inputValue()
  const fileTitle = await page.getByRole('textbox', { name: '图表名称', exact: true }).inputValue()
  const image = boundary.locator('image')
  const displayed = async () => decodeURIComponent(await image.getAttribute('xlink:href') || '')
  await name.fill('教务管理系统')
  await name.press('Tab')
  await expect.poll(displayed).toContain('教务管理系统')
  await expect(page.getByRole('textbox', { name: '图表名称', exact: true })).toHaveValue(fileTitle)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(name).toHaveValue(original)
  await expect.poll(displayed).toContain(original)
  await name.fill('   ')
  await name.press('Tab')
  await expect(name).toHaveValue(original)
  await expect(page.getByRole('status')).toContainText('系统名称不能为空')
  await name.fill('教务管理系统')
  await name.press('Tab')
  await page.getByRole('button', { name: '保存文件', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('文件已保存')
  await page.reload()
  await expect.poll(displayed).toContain('教务管理系统')
})
